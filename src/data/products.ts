export function sortProductsByPriority(list: Product[]): Product[] {
  return [...list].sort((a, b) => {
    const prioA = CATEGORY_PRIORITY[a.categorySlug] ?? 99;
    const prioB = CATEGORY_PRIORITY[b.categorySlug] ?? 99;
    return prioA - prioB;
  });
}

